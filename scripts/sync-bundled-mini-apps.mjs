import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { basename, resolve } from "node:path";
import process from "node:process";

const root = resolve(import.meta.dirname, "..");
const examplesDirectory = resolve(root, "examples");
const catalogOutputPath = resolve(
  root,
  "apps/mobile/src/generated/bundled-mini-apps.json",
);
const authoringTemplatePath = resolve(
  root,
  "docs/fixtures/agent-template.miniapp.js",
);
const mobileTemplateOutputPath = resolve(
  root,
  "apps/mobile/src/installer/template.ts",
);

const fileNames = (await readdir(examplesDirectory))
  .filter((fileName) => fileName.endsWith(".miniapp.js"))
  .sort();

const miniApps = await Promise.all(
  fileNames.map(async (fileName) => ({
    fileName: basename(fileName),
    source: normalizeLineEndings(
      await readFile(resolve(examplesDirectory, fileName), "utf8"),
    ),
  })),
);
const authoringTemplate = normalizeLineEndings(
  await readFile(authoringTemplatePath, "utf8"),
);

const outputs = [
  {
    path: catalogOutputPath,
    content: `${JSON.stringify(miniApps, null, 2)}\n`,
    label: "Bundled mini-app catalog",
  },
  {
    path: mobileTemplateOutputPath,
    content:
      "// Generated by scripts/sync-bundled-mini-apps.mjs. Do not edit directly.\n\n" +
      "export const NEW_MINI_APP_TEMPLATE =\n" +
      `  ${JSON.stringify(authoringTemplate)};\n`,
    label: "Mobile authoring template",
  },
];

if (process.argv.includes("--check")) {
  let stale = false;
  for (const output of outputs) {
    const current = await readFile(output.path, "utf8").catch(() => "");
    if (normalizeLineEndings(current) !== output.content) {
      console.error(`${output.label} is stale. Run pnpm sync:mini-apps.`);
      stale = true;
    }
  }
  if (stale) process.exitCode = 1;
} else {
  for (const output of outputs) {
    await mkdir(resolve(output.path, ".."), { recursive: true });
    await writeFile(output.path, output.content);
  }
}

function normalizeLineEndings(value) {
  return value.replace(/\r\n?/g, "\n");
}
