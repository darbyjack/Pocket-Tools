export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

export function normalizeText(value) {
  return value.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
}

export function slugifyHeading(value) {
  return value
    .normalize("NFKD")
    .toLowerCase()
    .replace(/<[^>]*>/g, "")
    .replace(/[`*_~[\](){}]/g, "")
    .replace(/&[a-z0-9#]+;/g, "")
    .replace(/[^\p{Letter}\p{Number}\s-]/gu, "")
    .trim()
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-");
}

export function extractTitle(markdown, fallbackTitle, extract = true) {
  const normalized = normalizeText(markdown);
  if (!extract) {
    return { title: fallbackTitle, body: normalized.trimEnd() };
  }

  const lines = normalized.split("\n");
  let inFence = false;

  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index];
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (inFence) {
      continue;
    }

    const match = /^#\s+(.+?)\s*$/.exec(line);
    if (!match) {
      continue;
    }

    lines.splice(index, 1);
    while (lines[index] === "") {
      lines.splice(index, 1);
    }
    return {
      title: match[1].trim(),
      body: lines.join("\n").trimEnd(),
    };
  }

  throw new Error(`Canonical Markdown is missing an H1: ${fallbackTitle}`);
}

export function removeMarkdownSection(markdown, heading) {
  const lines = markdown.split("\n");
  const startPattern = new RegExp(`^##\\s+${escapeRegExp(heading)}\\s*$`, "i");
  const start = lines.findIndex((line) => startPattern.test(line));
  if (start === -1) {
    return markdown;
  }

  let end = lines.length;
  for (let index = start + 1; index < lines.length; index += 1) {
    if (/^##\s+/.test(lines[index])) {
      end = index;
      break;
    }
  }

  lines.splice(start, end - start);
  return lines.join("\n").replace(/\n{3,}/g, "\n\n").trim();
}

function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function normalizedRepoPath(value) {
  const normalized = posix.normalize(value.replaceAll("\\", "/"));
  if (
    normalized === ".." ||
    normalized.startsWith("../") ||
    posix.isAbsolute(normalized)
  ) {
    throw new Error(`Documentation link escapes the repository: ${value}`);
  }
  return normalized.replace(/^\.\//, "");
}

function splitLinkDestination(rawDestination) {
  const trimmed = rawDestination.trim();
  if (trimmed.startsWith("<")) {
    const closing = trimmed.indexOf(">");
    if (closing === -1) {
      return { destination: trimmed, suffix: "" };
    }
    return {
      destination: trimmed.slice(1, closing),
      suffix: trimmed.slice(closing + 1),
      wrapped: true,
    };
  }

  const whitespace = trimmed.search(/\s/);
  if (whitespace === -1) {
    return { destination: trimmed, suffix: "" };
  }
  return {
    destination: trimmed.slice(0, whitespace),
    suffix: trimmed.slice(whitespace),
  };
}

function isExternalDestination(destination) {
  return /^(?:[a-z][a-z0-9+.-]*:|\/\/|#)/i.test(destination);
}

function findSourceRoute(target) {
  const exact = pages.find((page) => page.source === target);
  if (exact) {
    return exact.slug;
  }

  const matchingPrefix = Object.keys(sourceLinkRoutes)
    .sort((left, right) => right.length - left.length)
    .find(
      (prefix) =>
        target === prefix.replace(/\/$/, "") ||
        target.startsWith(`${prefix.replace(/\/$/, "")}/`),
    );

  return matchingPrefix ? sourceLinkRoutes[matchingPrefix] : undefined;
}

export function rewriteLinkDestination(sourcePath, rawDestination) {
  const parsed = splitLinkDestination(rawDestination);
  const destination = parsed.destination;

  if (
    !destination ||
    isExternalDestination(destination) ||
    destination.startsWith("/")
  ) {
    return rawDestination;
  }

  const hashIndex = destination.indexOf("#");
  const queryIndex = destination.indexOf("?");
  const boundaryIndexes = [hashIndex, queryIndex].filter((value) => value >= 0);
  const boundary = boundaryIndexes.length ? Math.min(...boundaryIndexes) : -1;
  const pathname = boundary === -1 ? destination : destination.slice(0, boundary);
  const suffix = boundary === -1 ? "" : destination.slice(boundary);

  if (!pathname) {
    return rawDestination;
  }

  const target = normalizedRepoPath(
    posix.join(posix.dirname(sourcePath), decodeURIComponent(pathname)),
  );

  const external = sourceLinkExternal[target];
  if (external) {
    return `${parsed.wrapped ? "<" : ""}${external}${suffix}${
      parsed.wrapped ? ">" : ""
    }${parsed.suffix}`;
  }

  const route = findSourceRoute(target);
  if (route !== undefined) {
    const rewritten = `${sitePath(route)}${suffix}`;
    return `${parsed.wrapped ? "<" : ""}${rewritten}${
      parsed.wrapped ? ">" : ""
    }${parsed.suffix}`;
  }

  const absoluteTarget = join(repoRoot, ...target.split("/"));
  if (!existsSync(absoluteTarget)) {
    throw new Error(
      `Unresolved local documentation link in ${sourcePath}: ${pathname} -> ${target}`,
    );
  }

  if (
    extname(target).toLowerCase() === ".md" ||
    target === "LICENSE" ||
    statSync(absoluteTarget).isDirectory()
  ) {
    throw new Error(
      `Local documentation link is not mapped in docs-map.mjs: ${sourcePath} -> ${target}`,
    );
  }

  const githubTarget = `${repositoryUrl}/blob/main/${target}${suffix}`;
  return `${parsed.wrapped ? "<" : ""}${githubTarget}${
    parsed.wrapped ? ">" : ""
  }${parsed.suffix}`;
}

export function rewriteMarkdownLinks(markdown, sourcePath) {
  const lines = normalizeText(markdown).split("\n");
  let fenceMarker = null;

  return lines
    .map((line) => {
      const fence = /^\s*(```|~~~)/.exec(line);
      if (fence) {
        fenceMarker = fenceMarker ? null : fence[1];
        return line;
      }
      if (fenceMarker) {
        return line;
      }

      let rewritten = line.replace(
        /(!?\[[^\]]*]\()([^)]+)(\))/g,
        (_match, opening, destination, closing) =>
          `${opening}${rewriteLinkDestination(sourcePath, destination)}${closing}`,
      );

      rewritten = rewritten.replace(
        /^(\s*\[[^\]]+]:\s*)(\S+)(.*)$/,
        (_match, opening, destination, suffix) =>
          `${opening}${rewriteLinkDestination(sourcePath, destination)}${suffix}`,
      );

      return rewritten;
    })
    .join("\n");
}

