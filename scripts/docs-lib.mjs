async function renderCanonicalPage(page) {
  const absoluteSource = join(repoRoot, ...page.source.split("/"));
  const original = normalizeText(await readFile(absoluteSource, "utf8"));
  const sourceHash = sha256(original);
  const extracted = extractTitle(
    original,
    page.title,
    page.extractTitle !== false,
  );

  let body;
  if (page.source === "LICENSE") {
    body = codeFence(extracted.body, "text");
  } else {
    body = rewriteMarkdownLinks(extracted.body, page.source);
  }

  if (page.landing) {
    body = removeMarkdownSection(body, "Start here");
    body = `${landingIntroduction()}\n\n${body}`;
  }

  const frontmatter = renderFrontmatter(
    page,
    page.title || extracted.title,
    editUrlForPage(page),
  );

  return {
    content: `${frontmatter}\n\n${GENERATED_WARNING}\n\n${body.trim()}\n`,
    sources: [{ path: page.source, sha256: sourceHash }],
  };
}

function pageOutputPath(page) {
  if (page.output) {
    return page.output;
  }
  return page.slug ? `${page.slug}/index.md` : "index.md";
}

export function assertDocumentationMap() {
  const groupIds = new Set(groups.map((group) => group.id));
  const seenSlugs = new Set();
  const seenSources = new Set();

  for (const page of pages) {
    if (!page.title || !page.description || !groupIds.has(page.group)) {
      throw new Error(`Invalid documentation map entry: ${JSON.stringify(page)}`);
    }
    if (!/^(?:|[a-z0-9]+(?:[a-z0-9./-]*[a-z0-9])?)$/.test(page.slug)) {
      throw new Error(`Documentation slug is not lowercase kebab-case: ${page.slug}`);
    }
    if (seenSlugs.has(page.slug)) {
      throw new Error(`Duplicate documentation slug: ${page.slug}`);
    }
    seenSlugs.add(page.slug);

    if (page.source) {
      if (seenSources.has(page.source)) {
        throw new Error(`Canonical source is mapped more than once: ${page.source}`);
      }
      seenSources.add(page.source);
      const absoluteSource = join(repoRoot, ...page.source.split("/"));
      if (!existsSync(absoluteSource)) {
        throw new Error(`Canonical documentation source does not exist: ${page.source}`);
      }
    } else if (!page.generator) {
      throw new Error(`Virtual documentation page has no generator: ${page.slug}`);
    }
  }
}

async function renderPage(page) {
  if (page.source) {
    return renderCanonicalPage(page);
  }
  switch (page.generator) {
    case "examples":
      return renderExamples(page);
    case "sdk-reference":
      return renderSdkReference(page);
    case "sdk-landing":
      return renderSdkLanding(page);
    case "backups-landing":
      return renderBackupsLanding(page);
    default:
      throw new Error(`Unknown documentation generator: ${page.generator}`);
  }
}

export async function generateDocumentation(destination) {
  assertDocumentationMap();
  await rm(destination, { recursive: true, force: true });
  await mkdir(destination, { recursive: true });

  const manifestEntries = [];

  for (const page of pages) {
    const rendered = await renderPage(page);
    const output = pageOutputPath(page);
    const absoluteOutput = join(destination, ...output.split("/"));
    await mkdir(dirname(absoluteOutput), { recursive: true });
    await writeFile(absoluteOutput, rendered.content, "utf8");
    manifestEntries.push({
      route: sitePath(page.slug),
      output,
      title: page.title,
      sources: rendered.sources,
      sha256: sha256(rendered.content),
    });
  }

  const manifest = {
    schemaVersion: 1,
    siteBase,
    entries: manifestEntries,
  };
  await writeFile(
    join(destination, "_generated-manifest.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
    "utf8",
  );

  return manifest;
}

async function listFiles(root, current = root) {
  const entries = await readdir(current, { withFileTypes: true });
  const files = [];

  for (const entry of entries) {
    const absolute = join(current, entry.name);
    if (entry.isDirectory()) {
      files.push(...(await listFiles(root, absolute)));
    } else {
      files.push(relative(root, absolute).replaceAll("\\", "/"));
    }
  }

  return files.sort((left, right) => left.localeCompare(right));
}

export async function compareDirectories(left, right) {
  const leftFiles = await listFiles(left);
  const rightFiles = await listFiles(right);
  if (JSON.stringify(leftFiles) !== JSON.stringify(rightFiles)) {
    throw new Error("Generated documentation file lists are not deterministic.");
  }

  for (const file of leftFiles) {
    const [leftContent, rightContent] = await Promise.all([
      readFile(join(left, ...file.split("/"))),
      readFile(join(right, ...file.split("/"))),
    ]);
    if (!leftContent.equals(rightContent)) {
      throw new Error(`Generated documentation is not deterministic: ${file}`);
    }
  }
}

function collectAnchors(markdown) {
  const anchors = new Set();
  const counts = new Map();
  let fenceMarker = null;

  for (const line of normalizeText(markdown).split("\n")) {
    const fence = /^\s*(```|~~~)/.exec(line);
    if (fence) {
      fenceMarker = fenceMarker ? null : fence[1];
      continue;
    }
    if (fenceMarker) {
      continue;
    }

    const heading = /^(#{2,6})\s+(.+?)\s*#*\s*$/.exec(line);
    if (heading) {
      const baseSlug = slugifyHeading(heading[2]);
      const count = counts.get(baseSlug) ?? 0;
      const slug = count === 0 ? baseSlug : `${baseSlug}-${count}`;
      counts.set(baseSlug, count + 1);
      anchors.add(slug);
    }

    for (const match of line.matchAll(/\bid=["']([^"']+)["']/g)) {
      anchors.add(match[1]);
    }
  }

  return anchors;
}

function collectLinks(markdown) {
  const links = [];
  let fenceMarker = null;

  for (const line of normalizeText(markdown).split("\n")) {
    const fence = /^\s*(```|~~~)/.exec(line);
    if (fence) {
      fenceMarker = fenceMarker ? null : fence[1];
      continue;
    }
    if (fenceMarker) {
      continue;
    }

    for (const match of line.matchAll(/!?\[[^\]]*]\(([^)]+)\)/g)) {
      const parsed = splitLinkDestination(match[1]);
      links.push(parsed.destination);
    }
    for (const match of line.matchAll(/\bhref=["']([^"']+)["']/g)) {
      links.push(match[1]);
    }
  }

  return links;
}

export async function validateGeneratedLinks(destination) {
  const outputBySlug = new Map(
    pages.map((page) => [page.slug, pageOutputPath(page)]),
  );
  const anchorsBySlug = new Map();

  for (const page of pages) {
    const output = pageOutputPath(page);
    const markdown = await readFile(join(destination, ...output.split("/")), "utf8");
    anchorsBySlug.set(page.slug, collectAnchors(markdown));
  }

  const errors = [];

  for (const page of pages) {
    const output = pageOutputPath(page);
    const markdown = await readFile(join(destination, ...output.split("/")), "utf8");

    if (
      /(?:[A-Za-z]:\\|file:\/\/|apps\/docs\/src\/content\/docs)/.test(markdown)
    ) {
      errors.push(`${output}: contains a local or generated-source path`);
    }

    for (const link of collectLinks(markdown)) {
      if (/^(?:[a-z][a-z0-9+.-]*:|\/\/)/i.test(link)) {
        continue;
      }

      if (link.startsWith("#")) {
        const fragment = decodeURIComponent(link.slice(1));
        if (fragment && !anchorsBySlug.get(page.slug)?.has(fragment)) {
          errors.push(`${output}: missing local anchor ${link}`);
        }
        continue;
      }

      if (!link.startsWith(siteBase)) {
        errors.push(`${output}: internal link is not base-aware: ${link}`);
        continue;
      }

      const withoutBase = link.slice(siteBase.length).replace(/^\/+/, "");
      const hashIndex = withoutBase.indexOf("#");
      const queryIndex = withoutBase.indexOf("?");
      const boundaries = [hashIndex, queryIndex].filter((value) => value >= 0);
      const boundary = boundaries.length ? Math.min(...boundaries) : -1;
      const routePart =
        boundary === -1 ? withoutBase : withoutBase.slice(0, boundary);
      const suffix = boundary === -1 ? "" : withoutBase.slice(boundary);
      const slug = routePart.replace(/^\/+|\/+$/g, "");

      if (!outputBySlug.has(slug)) {
        errors.push(`${output}: missing generated route ${link}`);
        continue;
      }

      const fragmentMatch = /#([^?]+)/.exec(suffix);
      if (fragmentMatch) {
        const fragment = decodeURIComponent(fragmentMatch[1]);
        if (!anchorsBySlug.get(slug)?.has(fragment)) {
          errors.push(`${output}: missing target anchor ${link}`);
        }
      }
    }
  }

  if (errors.length) {
    throw new Error(`Documentation link validation failed:\n- ${errors.join("\n- ")}`);
  }
}

export async function withGeneratedTemp(callback) {
  const temporaryRoot = await mkdtemp(join(tmpdir(), "pocket-tools-docs-"));
  const destination = join(temporaryRoot, "docs");
  try {
    await generateDocumentation(destination);
    return await callback(destination);
  } finally {
    await rm(temporaryRoot, { recursive: true, force: true });
  }
}
